"""Write src/data/gunk_followers.h: the follower sprite sheet and palettes of every species (by species id)."""
import os, re, sys
repo = sys.argv[1]
src = open(os.path.join(repo, 'include/constants/species.h')).read()
lines = ['// Gunk\'s follower sprites (src/gunk_follower.c). Generated by tools/gunk/gen_follower_header.py;',
         '// sprites from pokeemerald-expansion (graphics/gunk_followers/<species>/), originally aarant\'s followers branch.',
         '// Each sheet is six 32x32 frames: south x2, north x2, west x2 (east is west flipped).', '']
entries = []
for name, num in re.findall(r'#define SPECIES_(\w+) (\d+)', src):
    num = int(num)
    folder = name.lower()
    d = os.path.join(repo, 'graphics/gunk_followers', folder)
    if num == 0 or not os.path.isdir(d):
        continue
    c = ''.join(p.capitalize() for p in folder.split('_'))
    lines.append(f'static const u32 sFollowerPic_{c}[] = INCBIN_U32("graphics/gunk_followers/{folder}/overworld.4bpp");')
    lines.append(f'static const u16 sFollowerPal_{c}[] = INCBIN_U16("graphics/gunk_followers/{folder}/overworld_normal.gbapal");')
    lines.append(f'static const u16 sFollowerShinyPal_{c}[] = INCBIN_U16("graphics/gunk_followers/{folder}/overworld_shiny.gbapal");')
    entries.append(f'    [SPECIES_{name}] = {{sFollowerPic_{c}, sFollowerPal_{c}, sFollowerShinyPal_{c}}},')
lines += ['', 'static const struct GunkFollowerGfx sGunkFollowerGfx[NUM_SPECIES] = {'] + entries + ['};', '']
open(os.path.join(repo, 'src/data/gunk_followers.h'), 'w', newline='\n').write('\n'.join(lines))
print(len(entries))
